import React, { useState } from 'react';
import {
  ArrowLeft,
  ArrowRight,
  BookOpen,
  Building2,
  CheckCircle2,
  Eye,
  EyeOff,
  GraduationCap,
  KeyRound,
  Landmark,
  RefreshCw,
  ShieldAlert,
} from 'lucide-react';
import { evaluatePasswordStrength } from '../../lib/supabase';
import { AccountStatus, Profile, UserRole } from '../../types/portal';
import {
  Badge,
  Button,
  CampusLogo,
  GlassCard,
  Input,
  ThemeToggleButton,
} from '../ui/DesignSystem';

export type AuthScreenMode =
  | 'login'
  | 'signup'
  | 'verify-email'
  | 'forgot-password'
  | 'reset-password'
  | 'accept-invite'
  | 'pending-approval'
  | 'totp-challenge'
  | 'locked';

export type AccountRoleOption = 'student' | 'faculty' | 'super_admin' | 'admin';

export interface RegisteredAccountPayload {
  full_name: string;
  username: string;
  email: string;
  phone: string;
  role: UserRole;
  identifier_no: string;
  college_code?: string;
  college_name?: string;
  password?: string;
  initial_status?: AccountStatus;
}

interface AuthScreenProps {
  initialMode?: AuthScreenMode;
  initialRoleOption?: AccountRoleOption;
  profiles: Profile[];
  validCollegeCodes: { code: string; collegeName: string; scope: string }[];
  onRegisterCollegeCode: (code: string, collegeName: string) => void;
  onRefreshFromJson?: () => Promise<{
    profiles: Profile[];
    validCollegeCodes: { code: string; collegeName: string; scope: string }[];
  } | null>;
  currentTabId?: string;
  onBackToLanding: () => void;
  onAuthenticateUser: (profile: Profile) => void;
  onCreateAndAuthenticateUser: (payload: RegisteredAccountPayload) => void;
  onRecordAuditEvent: (action: string, metadata: Record<string, string | number | boolean>) => void;
  isDark?: boolean;
  onToggleTheme?: () => void;
}

const ROLE_OPTION_META: {
  id: 'super_admin' | 'faculty' | 'student';
  label: string;
  shortDesc: string;
  requiresSharedCode: boolean;
  createsCollegeCode: boolean;
  requiresOrganizerApproval: boolean;
  icon: React.FC<{ className?: string; strokeWidth?: number }>;
  idLabel: string;
  idPlaceholder: string;
}[] = [
  {
    id: 'super_admin',
    label: 'College Organizer',
    shortDesc:
      'Register your college & create a Unique College Code to share with students and teachers',
    requiresSharedCode: false,
    createsCollegeCode: true,
    requiresOrganizerApproval: false,
    icon: Landmark,
    idLabel: 'Organizer / Registration ID',
    idPlaceholder: 'e.g., ORG-2026-01',
  },
  {
    id: 'faculty',
    label: 'Teacher',
    shortDesc: 'Enter the Unique College Code shared by your College Organizer',
    requiresSharedCode: true,
    createsCollegeCode: false,
    requiresOrganizerApproval: false,
    icon: BookOpen,
    idLabel: 'Faculty / Employee ID',
    idPlaceholder: 'e.g., FAC-2026-08',
  },
  {
    id: 'student',
    label: 'Student',
    shortDesc:
      'Enter the Unique College Code generated by your College Organizer to join your specific college platform',
    requiresSharedCode: true,
    createsCollegeCode: false,
    requiresOrganizerApproval: true,
    icon: GraduationCap,
    idLabel: 'Student Enrolment / Roll Number',
    idPlaceholder: 'e.g., 26CSE104',
  },
];

const ADMIN_ROLE_META = {
  id: 'admin' as const,
  label: 'Admin',
  shortDesc: 'Platform administrator with multi-college governance and workspace inspection',
  requiresSharedCode: false,
  createsCollegeCode: false,
  requiresOrganizerApproval: false,
  icon: ShieldAlert,
  idLabel: 'Platform Administrator ID',
  idPlaceholder: 'ADM-2026-01',
};

export const AuthScreen: React.FC<AuthScreenProps> = ({
  initialMode = 'login',
  initialRoleOption = 'student',
  profiles,
  validCollegeCodes,
  onRegisterCollegeCode,
  onRefreshFromJson,
  currentTabId,
  onBackToLanding,
  onAuthenticateUser,
  onCreateAndAuthenticateUser,
  onRecordAuditEvent,
  isDark = false,
  onToggleTheme,
}) => {
  const normalizedInitialMode: 'login' | 'signup' | 'forgot-password' | 'locked' =
    initialMode === 'signup' || initialMode === 'accept-invite'
      ? 'signup'
      : initialMode === 'forgot-password'
        ? 'forgot-password'
        : 'login';

  const [mode, setMode] = useState<'login' | 'signup' | 'forgot-password' | 'locked'>(
    normalizedInitialMode
  );
  const [selectedRole, setSelectedRole] = useState<AccountRoleOption>(
    initialMode === 'accept-invite' ? 'faculty' : initialRoleOption
  );

  // Form fields
  const [fullName, setFullName] = useState('');
  const [username, setUsername] = useState('');
  const [email, setEmail] = useState('');
  const [phone, setPhone] = useState('');
  const [identifierNo, setIdentifierNo] = useState('');
  const [collegeName, setCollegeName] = useState('');
  const [collegeCode, setCollegeCode] = useState('');
  const [password, setPassword] = useState('');
  const [showPassword, setShowPassword] = useState(false);
  const [rememberMe, setRememberMe] = useState(true);
  const [failedAttempts, setFailedAttempts] = useState(0);
  const [formError, setFormError] = useState<string | null>(null);
  const [formNotice, setFormNotice] = useState<string | null>(null);
  const activeRoleMeta =
    selectedRole === 'admin'
      ? ADMIN_ROLE_META
      : ROLE_OPTION_META.find((r) => r.id === selectedRole) || ROLE_OPTION_META[0];
  const pwdStrength = evaluatePasswordStrength(password);

  // Verify whether a code entered by Student, Teacher or Admin matches a code created by a College Organizer
  const verifyOrganizerCode = (
    inputCode: string | undefined | null,
    codesList = validCollegeCodes,
    profilesList = profiles
  ): { valid: boolean; matchedName?: string } => {
    const clean = (inputCode || '').trim().toUpperCase();
    if (!clean) return { valid: false };

    // 1. Authoritative check: validCollegeCodes list
    const found = codesList.find((c) => (c.code || '').trim().toUpperCase() === clean);
    if (found) {
      return { valid: true, matchedName: found.collegeName };
    }

    // 2. Secondary check: existing super_admin profiles
    const orgProfile = profilesList.find(
      (p) => p.role === 'super_admin' && (p.college_code || '').trim().toUpperCase() === clean
    );
    if (orgProfile) {
      return { valid: true, matchedName: orgProfile.college_name || 'Registered College' };
    }
    return { valid: false };
  };

  // Helper for College Organizer to auto-generate a random unique code
  const handleGenerateCustomOrganizerCode = () => {
    const prefix = (
      collegeName.trim().replace(/[^a-zA-Z]/g, '').slice(0, 4) || 'INST'
    ).toUpperCase();
    const randomSuffix = Math.floor(1000 + Math.random() * 9000);
    const newCode = `${prefix}-${randomSuffix}`;
    setCollegeCode(newCode);
    setFormError(null);
  };

  const handleCreateAccount = async (e: React.FormEvent) => {
    e.preventDefault();
    setFormError(null);
    setFormNotice(null);

    if (!fullName.trim() || !username.trim() || !email.trim().includes('@')) {
      setFormError('Please enter your full name, username, and a valid email address.');
      return;
    }

    if (password.length < 6) {
      setFormError('Password must be at least 6 characters long.');
      return;
    }

    // Fetch latest JSON state from server so parallel tabs never collide or miss newly created codes/accounts
    const freshJson = onRefreshFromJson ? await onRefreshFromJson() : null;
    const latestProfiles = freshJson?.profiles || profiles;
    const latestCodes = freshJson?.validCollegeCodes || validCollegeCodes;

    // Match by both email AND role so accounts for different roles never collide
    const existingSameRole = latestProfiles.find(
      (p) =>
        (p.email.trim().toLowerCase() === email.trim().toLowerCase() || 
         (p.username && p.username.trim().toLowerCase() === username.trim().toLowerCase())) &&
        p.role === selectedRole
    );
    if (existingSameRole) {
      setFormError(
        `An account with this email or username already exists for the ${activeRoleMeta.label} role.`
      );
      return;
    }

    let finalCollegeCode: string | undefined = undefined;
    let finalCollegeName = collegeName.trim() || (selectedRole === 'super_admin' ? '' : 'Institution Workspace');

    // CASE 1: COLLEGE ORGANIZER -> Creates their own Unique College Code to share with Students, Teachers & Admins
    if (selectedRole === 'super_admin') {
      if (!collegeName.trim()) {
        setFormError('Please enter your College or Institution Name.');
        return;
      }
      const cleanOrganizerCode = collegeCode.trim().toUpperCase();
      if (!cleanOrganizerCode || cleanOrganizerCode.length < 4) {
        setFormError(
          'Please create a Unique College Code (at least 4 characters, e.g. COLL-1234) so you can share it with your Students, Teachers, and Admins.'
        );
        return;
      }
      finalCollegeCode = cleanOrganizerCode;
      finalCollegeName = collegeName.trim();
      onRegisterCollegeCode(finalCollegeCode, finalCollegeName);
    }

    // CASE 2: STUDENT, TEACHER / FACULTY, or ADMIN -> Must enter a Unique College Code created by a College Organizer
    if (activeRoleMeta.requiresSharedCode) {
      const cleanInputCode = collegeCode.trim().toUpperCase();
      let codeCheck = verifyOrganizerCode(cleanInputCode, latestCodes, latestProfiles);
      
      // If code not found, try one more immediate refresh from JSON database in case of parallel sync
      if (!codeCheck.valid && onRefreshFromJson) {
        const retryJson = await onRefreshFromJson();
        if (retryJson) {
          codeCheck = verifyOrganizerCode(cleanInputCode, retryJson.validCollegeCodes, retryJson.profiles);
        }
      }

      if (!codeCheck.valid) {
        setFormError(
          `Invalid Unique College Code "${cleanInputCode}". Please enter the exact Unique College Code generated by your College Organizer so you join that specific college platform.`
        );
        return;
      }
      finalCollegeCode = cleanInputCode;
      finalCollegeName = codeCheck.matchedName || finalCollegeName;
    }

    const finalIdentifier =
      identifierNo.trim().toUpperCase() ||
      (selectedRole === 'student'
        ? `26STU${Math.floor(100 + Math.random() * 900)}`
        : `${selectedRole.toUpperCase().slice(0, 3)}-${Math.floor(100 + Math.random() * 900)}`);

    // Students joining via a College Organizer's code start as 'pending' so the Organizer can review and approve them
    const initialStatus: AccountStatus =
      selectedRole === 'student' ? 'pending' : 'active';

    onRecordAuditEvent('ACCOUNT_CREATED_AND_AUTHENTICATED', {
      role: selectedRole,
      email: email.trim().toLowerCase(),
      college_code: finalCollegeCode || 'UNASSIGNED',
      status: initialStatus,
    });

    onCreateAndAuthenticateUser({
      full_name: fullName.trim(),
      username: username.trim().toLowerCase(),
      email: email.trim().toLowerCase(),
      phone: phone.trim() || '+91 98000 00000',
      role: selectedRole,
      identifier_no: finalIdentifier,
      college_code: finalCollegeCode,
      college_name: finalCollegeName,
      password,
      initial_status: initialStatus,
    });
  };

  const handleLoginSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setFormError(null);
    setFormNotice(null);

    if (failedAttempts >= 4) {
      const nextCount = failedAttempts + 1;
      setFailedAttempts(nextCount);
      onRecordAuditEvent('AUTH_FAILED_LOGIN_LOCKOUT', {
        email_attempted: email,
        attempts: nextCount,
      });
      setMode('locked');
      return;
    }

    if (!email.trim().includes('@') || !password.trim()) {
      setFormError('Please enter your email address and password.');
      return;
    }

    // Platform Admin authentication via authoritative server endpoint
    if (selectedRole === 'admin') {
      try {
        const res = await fetch('/api/auth/admin-login', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ email: email.trim(), password }),
        });
        const result = await res.json();
        if (!res.ok || (!result.ok && !result.success)) {
          const nextCount = failedAttempts + 1;
          setFailedAttempts(nextCount);
          setFormError(result.error || 'Invalid platform administrator credentials.');
          return;
        }
        onRecordAuditEvent('AUTH_ADMIN_SIGNIN_SUCCESS', {
          role: 'admin',
          email: result.profile.email,
        });
        onAuthenticateUser(result.profile);
        return;
      } catch {
        setFormError('Failed to contact server for Admin authentication. Please try again.');
        return;
      }
    }

    // Fetch latest JSON state so parallel tabs have the freshest accounts and college codes
    const freshJson = onRefreshFromJson ? await onRefreshFromJson() : null;
    const latestProfiles = freshJson?.profiles || profiles;
    const latestCodes = freshJson?.validCollegeCodes || validCollegeCodes;

    // Match by BOTH email AND selectedRole so accounts across different roles never overwrite each other
    const matchedProfile =
      latestProfiles.find(
        (p) =>
          p.email.trim().toLowerCase() === email.trim().toLowerCase() &&
          p.role === selectedRole
      ) ||
      (selectedRole === 'student'
        ? latestProfiles.find(
            (p) =>
              p.email.trim().toLowerCase() === email.trim().toLowerCase() &&
              p.role === 'student'
          )
        : undefined);

    if (matchedProfile) {
      if (matchedProfile.password && matchedProfile.password !== password) {
        const nextCount = failedAttempts + 1;
        setFailedAttempts(nextCount);
        setFormError(
          `Incorrect password for this account. (${5 - nextCount} attempts remaining)`
        );
        return;
      }

      // For College Organizer (super_admin), always prefer their saved profile code
      const effectiveCode = matchedProfile.college_code || undefined;
      const verifiedCollegeName = matchedProfile.college_name || undefined;

      if (selectedRole === 'super_admin' && effectiveCode) {
        onRegisterCollegeCode(
          effectiveCode,
          verifiedCollegeName || 'Registered Institution'
        );
      }

      // Preserve 'pending' or 'active' status so students require Organizer approval before accessing pages
      const targetProfile: Profile = {
        ...matchedProfile,
        role: matchedProfile.role,
        status:
          matchedProfile.role === 'student'
            ? matchedProfile.status || 'pending'
            : matchedProfile.status || 'active',
        college_code: effectiveCode,
        college_name: verifiedCollegeName,
        updated_at: new Date().toISOString(),
      };

      onRecordAuditEvent('AUTH_SIGNIN_SUCCESS', {
        role: targetProfile.role,
        email: targetProfile.email,
        college_code: targetProfile.college_code || 'NONE',
        status: targetProfile.status,
      });
      onAuthenticateUser(targetProfile);
      return;
    }

    // CRITICAL FIX: If account doesn't exist, DO NOT auto-create. Error out.
    setFormError(`No ${activeRoleMeta.label} account found with the email "${email}". Please check your credentials or create an account.`);
    onRecordAuditEvent('AUTH_SIGNIN_FAILED_NOT_FOUND', {
      role: selectedRole,
      email_attempted: email,
    });
  };

  return (
    <div className="min-h-screen w-full bg-[var(--bg)] text-[var(--text)] relative overflow-hidden">
      <div className="relative z-10 min-h-screen grid grid-cols-1 lg:grid-cols-12">
        {/* Left Column: How Institutional Role Onboarding Works */}
        <div className="hidden lg:flex lg:col-span-5 flex-col justify-between glass-strong border-r border-[var(--glass-border)] p-10 text-ink">
          <div className="space-y-6">
            <div className="flex items-center justify-between gap-4">
              <button
                type="button"
                onClick={onBackToLanding}
                className="inline-flex items-center gap-2 text-xs font-semibold text-muted hover:text-ink cursor-pointer"
              >
                <ArrowLeft className="h-4 w-4" strokeWidth={1.75} />
                Return to Platform Home
              </button>
              <Badge tone="accent">Verified Institutional Gateway</Badge>
            </div>

            <div>
              <CampusLogo subtitle="Role-Based Authentication Gateway" />
              <h2 className="mt-5 font-editorial text-2xl font-bold text-ink">
                College Code Onboarding &amp; Organizer Approval
              </h2>
              <p className="mt-2 text-sm text-muted leading-relaxed">
                Every college operates its own isolated platform. The{' '}
                <strong className="text-ink">College Organizer</strong> registers first, generates a{' '}
                <strong className="text-ink">Unique College Code</strong>, and shares it with their{' '}
                <strong className="text-ink">Students, Teachers, and Admins</strong> during account creation.
              </p>
            </div>

            {/* Step-by-Step Institutional Flow */}
            <GlassCard padding="md" className="space-y-3">
              <div className="text-xs font-bold uppercase tracking-wider text-accent">
                3-Step Institutional Onboarding
              </div>
              <div className="divide-y divide-[var(--glass-border-subtle)] text-xs">
                <div className="py-3 flex items-start justify-between gap-3">
                  <div>
                    <div className="font-semibold text-ink">1. College Organizer Creates Code</div>
                    <div className="mt-0.5 text-muted leading-relaxed">
                      Registers the institution and generates a Unique College Code (e.g.{' '}
                      <code className="font-mono font-semibold text-accent">COLL-1234</code>).
                    </div>
                  </div>
                  <Badge tone="brass">Creates Code</Badge>
                </div>

                <div className="py-3 flex items-start justify-between gap-3">
                  <div>
                    <div className="font-semibold text-ink">
                      2. Students Register with Code &amp; Get Approved
                    </div>
                    <div className="mt-0.5 text-muted leading-relaxed">
                      Students enter their Organizer&apos;s Unique College Code when creating an account.
                      After signing in, portal pages unlock once the College Organizer approves them.
                    </div>
                  </div>
                  <Badge tone="warning">Organizer Approval</Badge>
                </div>

                <div className="py-3 flex items-start justify-between gap-3">
                  <div>
                    <div className="font-semibold text-ink">
                      3. Sign In with Email &amp; Password
                    </div>
                    <div className="mt-0.5 text-muted leading-relaxed">
                      Returning Students, Faculty, and Admins sign in directly with their registered
                      email and password — no code needed on sign-in.
                    </div>
                  </div>
                  <Badge tone="success">Direct Sign-In</Badge>
                </div>
              </div>
            </GlassCard>
          </div>

          <div className="border-t border-[var(--glass-border-subtle)] pt-5 text-xs text-muted flex items-center justify-between">
            <span>Campus Portal · Multi-Role Institutional Access Control</span>
            <span className="font-mono text-[11px] text-accent">2FA &amp; Role Verified</span>
          </div>
        </div>

        {/* Right Column: Real-Time Role Registration & Login Forms */}
        <div className="flex flex-col justify-center px-6 py-10 sm:px-12 lg:col-span-7">
          <div className="mx-auto w-full max-w-xl">
            {/* Top Mobile & Theme Bar */}
            <div className="mb-6 flex items-center justify-between gap-2">
              <button
                type="button"
                onClick={onBackToLanding}
                className="inline-flex items-center gap-1.5 text-xs font-semibold text-muted hover:text-ink cursor-pointer lg:hidden"
              >
                <ArrowLeft className="h-4 w-4" strokeWidth={1.75} />
                Back to Home
              </button>
              <div className="lg:hidden">
                <CampusLogo compact />
              </div>
              <div className="ml-auto flex items-center gap-2">
                {onToggleTheme && <ThemeToggleButton isDark={isDark} onToggle={onToggleTheme} />}
              </div>
            </div>

            {/* Primary Auth Mode Switcher: Create Account vs Sign In */}
            <div className="mb-6 grid grid-cols-3 gap-1.5 glass p-1.5 rounded-[14px]">
              {(
                [
                  ['signup', 'Create Account'],
                  ['login', 'Sign In'],
                  ['forgot-password', 'Reset Password'],
                ] as const
              ).map(([m, label]) => (
                <button
                  key={m}
                  type="button"
                  onClick={() => {
                    setFormError(null);
                    setFormNotice(null);
                    setMode(m);
                    if (m === 'signup' && selectedRole === 'admin') {
                      setSelectedRole('student');
                    }
                  }}
                  className={`rounded-[10px] px-3 py-2 text-xs font-semibold transition-all cursor-pointer ${
                    mode === m
                      ? 'bg-accent text-white shadow-sm'
                      : 'text-muted hover:text-ink'
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>

            {/* Role Selection Cards */}
            {(mode === 'signup' || mode === 'login') && (
              <div className="mb-6 space-y-2.5">
                <div className="flex items-center justify-between">
                  <label className="text-xs font-bold uppercase tracking-wider text-ink">
                    {mode === 'login' ? 'Sign In Options' : 'Select Account Type'}
                  </label>
                  <Badge
                    tone={
                      selectedRole === 'admin'
                        ? 'accent'
                        : mode === 'login'
                          ? activeRoleMeta.requiresOrganizerApproval
                            ? 'warning'
                            : 'success'
                          : activeRoleMeta.createsCollegeCode
                            ? 'brass'
                            : activeRoleMeta.requiresOrganizerApproval
                              ? 'warning'
                              : 'accent'
                    }
                  >
                    {selectedRole === 'admin'
                      ? 'Platform Administrator Credentials'
                      : mode === 'login'
                        ? activeRoleMeta.requiresOrganizerApproval
                          ? 'Email & Password · Approval Gate'
                          : 'Direct College Credentials'
                        : activeRoleMeta.createsCollegeCode
                          ? 'Creates Unique College Code'
                          : activeRoleMeta.requiresOrganizerApproval
                            ? 'Requires College Code + Approval'
                            : 'Requires College Code'}
                  </Badge>
                </div>

                {/* 3 College Roles: College Organizer, Teacher, Student */}
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5">
                  {ROLE_OPTION_META.map((roleOpt) => {
                    const IconComp = roleOpt.icon;
                    const isSelected = selectedRole === roleOpt.id;
                    return (
                      <button
                        key={roleOpt.id}
                        type="button"
                        onClick={() => {
                          setSelectedRole(roleOpt.id);
                          setFormError(null);
                        }}
                        className={`flex flex-col items-start justify-between rounded-[14px] border p-3.5 text-left transition-all cursor-pointer ${
                          isSelected
                            ? 'border-accent bg-[var(--accent-soft)] text-ink ring-1 ring-accent'
                            : 'glass text-muted hover:border-indigo-400/50 hover:text-ink'
                        }`}
                      >
                        <div className="flex w-full items-center justify-between">
                          <IconComp
                            className={`h-4 w-4 ${isSelected ? 'text-accent' : 'text-muted'}`}
                            strokeWidth={1.85}
                          />
                          {roleOpt.createsCollegeCode ? (
                            <KeyRound className="h-3.5 w-3.5 text-indigo-500" strokeWidth={1.75} />
                          ) : (
                            <CheckCircle2 className="h-3.5 w-3.5 text-accent" strokeWidth={1.75} />
                          )}
                        </div>
                        <div className="mt-2.5">
                          <div className="text-xs font-bold text-ink">
                            {mode === 'login' ? `Sign in as ${roleOpt.label}` : roleOpt.label}
                          </div>
                          <div className="mt-0.5 text-[10px] text-muted leading-tight">
                            {mode === 'login'
                              ? 'College Portal Sign In'
                              : roleOpt.createsCollegeCode
                                ? 'Create Code'
                                : roleOpt.id === 'student'
                                  ? 'Join via Code'
                                  : 'Enter Code'}
                          </div>
                        </div>
                      </button>
                    );
                  })}
                </div>

                {/* Dedicated Admin Sign-In (placed below Organizer, Teacher, and Student options for Sign In only) */}
                {mode === 'login' && (
                  <div className="pt-1.5">
                    <button
                      type="button"
                      onClick={() => {
                        setSelectedRole('admin');
                        setFormError(null);
                      }}
                      className={`w-full flex items-center justify-between rounded-[14px] border p-3.5 text-left transition-all cursor-pointer ${
                        selectedRole === 'admin'
                          ? 'border-indigo-500 bg-indigo-500/15 text-ink ring-1 ring-indigo-500'
                          : 'glass text-muted hover:border-indigo-400/50 hover:text-ink'
                      }`}
                    >
                      <div className="flex items-center gap-3">
                        <div
                          className={`flex h-8 w-8 items-center justify-center rounded-xl transition-colors ${
                            selectedRole === 'admin'
                              ? 'bg-indigo-600 text-white shadow-sm'
                              : 'bg-muted/10 text-muted'
                          }`}
                        >
                          <ShieldAlert className="h-4 w-4" strokeWidth={1.85} />
                        </div>
                        <div>
                          <div className="text-xs font-bold text-ink">Sign in as Admin</div>
                          <div className="text-[10px] text-muted">
                            Platform-wide governance &amp; multi-college isolated workspace
                          </div>
                        </div>
                      </div>
                      <Badge tone={selectedRole === 'admin' ? 'accent' : 'neutral'}>
                        {selectedRole === 'admin' ? 'Active Selection' : 'Admin Portal'}
                      </Badge>
                    </button>
                  </div>
                )}
              </div>
            )}

            {/* CREATE ACCOUNT FORM */}
            {mode === 'signup' && (
              <GlassCard padding="lg">
                <form onSubmit={handleCreateAccount} className="space-y-4">
                  <div className="border-b border-[var(--glass-border-subtle)] pb-4">
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-xs font-bold text-accent uppercase tracking-wider">
                        New {activeRoleMeta.label} Account
                      </span>
                      <Badge
                        tone={
                          activeRoleMeta.createsCollegeCode
                            ? 'brass'
                            : activeRoleMeta.requiresOrganizerApproval
                              ? 'warning'
                              : 'accent'
                        }
                        dot
                      >
                        {activeRoleMeta.createsCollegeCode
                          ? 'Step 1 · Create College Code'
                          : activeRoleMeta.requiresOrganizerApproval
                            ? 'Step 2 · Join College & Request Approval'
                            : 'Requires Organizer Code'}
                      </Badge>
                    </div>
                    <h1 className="mt-1.5 font-editorial text-2xl font-bold text-ink">
                      Create {activeRoleMeta.label} Account
                    </h1>
                    <p className="mt-1 text-xs text-muted">{activeRoleMeta.shortDesc}</p>
                  </div>

                  {formError && (
                    <div
                      role="alert"
                      className="rounded-[12px] border border-danger/40 bg-danger/10 p-3 text-xs font-medium text-danger"
                    >
                      {formError}
                    </div>
                  )}

                  {formNotice && (
                    <div
                      role="status"
                      className="rounded-[12px] border border-success/40 bg-success/10 p-3 text-xs font-medium text-success"
                    >
                      {formNotice}
                    </div>
                  )}

                  <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
                    <Input
                      label="Full Name"
                      placeholder="e.g. John Doe"
                      value={fullName}
                      onChange={(e) => setFullName(e.target.value)}
                      required
                    />
                    <Input
                      label="Username"
                      placeholder="e.g. johndoe01"
                      value={username}
                      onChange={(e) => setUsername(e.target.value.toLowerCase())}
                      required
                    />
                    <Input
                      label="Email Address"
                      type="email"
                      placeholder="name@college.edu"
                      value={email}
                      onChange={(e) => setEmail(e.target.value)}
                      required
                    />
                  </div>

                  <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
                    <Input
                      label={activeRoleMeta.idLabel}
                      placeholder={activeRoleMeta.idPlaceholder}
                      value={identifierNo}
                      onChange={(e) => setIdentifierNo(e.target.value)}
                      required
                    />
                    <Input
                      label="Contact Phone"
                      placeholder="+91 98450 00000"
                      value={phone}
                      onChange={(e) => setPhone(e.target.value)}
                    />
                  </div>

                  {/* COLLEGE ORGANIZER: CREATE YOUR OWN UNIQUE COLLEGE CODE TO SHARE */}
                  {activeRoleMeta.createsCollegeCode && (
                    <div className="rounded-[14px] border border-indigo-500/30 bg-[var(--accent-soft)]/50 p-4 space-y-3">
                      <div className="flex flex-wrap items-center justify-between gap-2">
                        <div className="flex items-center gap-2 text-xs font-bold text-ink">
                          <KeyRound className="h-4 w-4 text-accent" strokeWidth={1.85} />
                          <span>Create Your Institution&apos;s Unique College Code</span>
                        </div>
                        <button
                          type="button"
                          onClick={handleGenerateCustomOrganizerCode}
                          className="inline-flex items-center gap-1.5 rounded-[10px] border border-[var(--accent)] bg-[var(--surface)] px-2.5 py-1 text-[11px] font-semibold text-[var(--accent-text)] hover:bg-[var(--accent)] hover:text-[var(--on-accent)] transition-colors cursor-pointer"
                        >
                          <RefreshCw className="h-3 w-3" strokeWidth={1.75} />
                          Auto-Generate Code
                        </button>
                      </div>

                      <Input
                        label="College / Institution Name"
                        placeholder="e.g., National Institute of Technology"
                        value={collegeName}
                        onChange={(e) => setCollegeName(e.target.value)}
                        required
                      />

                      <Input
                        label="Define Unique College Code (Share with your Students, Teachers & Admins)"
                        placeholder="Type your own code (e.g., NIT-2026) or click Auto-Generate"
                        value={collegeCode}
                        onChange={(e) => setCollegeCode(e.target.value.toUpperCase())}
                        className="font-mono uppercase tracking-wider"
                        hint="Share this Unique College Code with your Students, Teachers, and Admins so they join your specific college platform."
                        required
                      />
                    </div>
                  )}

                  {/* STUDENT, TEACHER / ADMIN: ENTER THE UNIQUE COLLEGE CODE SHARED BY COLLEGE ORGANIZER (ONLY DURING ACCOUNT CREATION) */}
                  {activeRoleMeta.requiresSharedCode && (
                    <div className="rounded-[14px] border border-indigo-500/30 bg-[var(--accent-soft)]/50 p-4 space-y-2.5">
                      <div className="flex items-center justify-between gap-2">
                        <div className="flex items-center gap-2 text-xs font-bold text-ink">
                          <KeyRound className="h-4 w-4 text-accent" strokeWidth={1.85} />
                          <span>Enter Unique College Code (Generated by College Organizer)</span>
                        </div>
                        {selectedRole === 'student' && (
                          <Badge tone="warning">Requires Organizer Approval</Badge>
                        )}
                      </div>
                      <Input
                        label="Unique College Code *"
                        placeholder="e.g., COLL-1234"
                        value={collegeCode}
                        onChange={(e) => setCollegeCode(e.target.value.toUpperCase())}
                        className="font-mono uppercase tracking-wider"
                        hint={
                          selectedRole === 'student'
                            ? 'Enter the Unique College Code generated by your College Organizer to join your specific college platform. Your Organizer will review and approve your request.'
                            : "Ask your College Organizer for your institution's Unique College Code."
                        }
                        required
                      />
                    </div>
                  )}

                  <div className="relative">
                    <Input
                      label="Create Password"
                      type={showPassword ? 'text' : 'password'}
                      placeholder="Enter a strong password"
                      value={password}
                      onChange={(e) => setPassword(e.target.value)}
                      required
                    />
                    <button
                      type="button"
                      onClick={() => setShowPassword(!showPassword)}
                      aria-label={showPassword ? 'Hide password' : 'Show password'}
                      className="absolute right-3.5 top-8 text-muted hover:text-ink cursor-pointer"
                    >
                      {showPassword ? (
                        <EyeOff className="h-4 w-4" strokeWidth={1.75} />
                      ) : (
                        <Eye className="h-4 w-4" strokeWidth={1.75} />
                      )}
                    </button>
                  </div>

                  {password.length > 0 && (
                    <div className="space-y-1">
                      <div className="flex items-center justify-between text-xs">
                        <span className="text-muted">Password Security</span>
                        <span
                          className={`font-mono font-medium ${
                            pwdStrength.score >= 3 ? 'text-success' : 'text-warning'
                          }`}
                        >
                          {pwdStrength.label}
                        </span>
                      </div>
                      <div className="grid grid-cols-4 gap-1.5">
                        {[1, 2, 3, 4].map((bar) => (
                          <div
                            key={bar}
                            className={`h-1.5 rounded-full ${
                              pwdStrength.score >= bar
                                ? pwdStrength.score >= 3
                                  ? 'bg-success'
                                  : 'bg-warning'
                                : 'bg-[var(--border)]'
                            }`}
                          />
                        ))}
                      </div>
                    </div>
                  )}

                  <Button type="submit" variant="primary" size="lg" className="w-full">
                    {activeRoleMeta.createsCollegeCode
                      ? 'Create Organizer Account & Register College Code'
                      : selectedRole === 'student'
                        ? 'Verify College Code & Join College Platform'
                        : `Verify Code & Create ${activeRoleMeta.label} Account`}
                    <ArrowRight className="h-4 w-4" strokeWidth={1.85} />
                  </Button>
                </form>
              </GlassCard>
            )}

            {/* SIGN IN FORM (NO UNIQUE COLLEGE CODE ASKED ON SIGN IN) */}
            {mode === 'login' && (
              <GlassCard padding="lg">
                <form onSubmit={handleLoginSubmit} className="space-y-4">
                  <div className="border-b border-[var(--glass-border-subtle)] pb-4">
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-xs font-bold text-accent uppercase tracking-wider">
                        {activeRoleMeta.label} Sign In
                      </span>
                      <Badge
                        tone={activeRoleMeta.requiresOrganizerApproval ? 'warning' : 'success'}
                        dot
                      >
                        {activeRoleMeta.requiresOrganizerApproval
                          ? 'Organizer Approval Gate Active'
                          : 'Direct Credentials Access'}
                      </Badge>
                    </div>
                    <h1 className="mt-1.5 font-editorial text-2xl font-bold text-ink">
                      Sign in as {activeRoleMeta.label}
                    </h1>
                    <p className="mt-1 text-xs text-muted">
                      {selectedRole === 'student'
                        ? 'Enter your registered student email and password. You will enter the portal immediately; full page access unlocks once your College Organizer approves your account.'
                        : `Enter your registered ${activeRoleMeta.label.toLowerCase()} email and password to access your workspace.`}
                    </p>
                  </div>

                  {formError && (
                    <div
                      role="alert"
                      className="rounded-[12px] border border-danger/40 bg-danger/10 p-3 text-xs font-medium text-danger"
                    >
                      {formError}
                    </div>
                  )}

                  <Input
                    label="Registered Email Address"
                    type="email"
                    placeholder={`Enter your ${activeRoleMeta.label.toLowerCase()} email`}
                    value={email}
                    onChange={(e) => setEmail(e.target.value)}
                    required
                    autoComplete="email"
                  />

                  <div className="relative">
                    <Input
                      label="Password"
                      type={showPassword ? 'text' : 'password'}
                      placeholder="Enter your password"
                      value={password}
                      onChange={(e) => setPassword(e.target.value)}
                      required
                      autoComplete="current-password"
                    />
                    <button
                      type="button"
                      onClick={() => setShowPassword(!showPassword)}
                      aria-label={showPassword ? 'Hide password' : 'Show password'}
                      className="absolute right-3.5 top-8 text-muted hover:text-ink cursor-pointer"
                    >
                      {showPassword ? (
                        <EyeOff className="h-4 w-4" strokeWidth={1.75} />
                      ) : (
                        <Eye className="h-4 w-4" strokeWidth={1.75} />
                      )}
                    </button>
                  </div>

                  <div className="flex items-center justify-between text-xs">
                    <label className="inline-flex items-center gap-2 text-muted cursor-pointer">
                      <input
                        type="checkbox"
                        checked={rememberMe}
                        onChange={(e) => setRememberMe(e.target.checked)}
                        className="rounded border-line"
                      />
                      <span>Keep session active on this tab</span>
                    </label>
                    <button
                      type="button"
                      onClick={() => setMode('forgot-password')}
                      className="font-semibold text-accent hover:underline cursor-pointer"
                    >
                      Forgot password?
                    </button>
                  </div>

                  <Button type="submit" variant="primary" size="lg" className="w-full">
                    Sign In to {activeRoleMeta.label} Portal
                    <ArrowRight className="h-4 w-4" strokeWidth={1.85} />
                  </Button>

                  <div className="pt-2 border-t border-[var(--glass-border-subtle)] text-center text-xs text-muted">
                    Don&apos;t have an account yet?{' '}
                    <button
                      type="button"
                      onClick={() => {
                        setFormError(null);
                        setMode('signup');
                      }}
                      className="font-semibold text-accent hover:underline cursor-pointer"
                    >
                      Create a {activeRoleMeta.label} account
                    </button>
                  </div>
                </form>
              </GlassCard>
            )}

            {/* FORGOT PASSWORD */}
            {mode === 'forgot-password' && (
              <GlassCard padding="lg" className="space-y-4">
                <h1 className="font-editorial text-2xl font-bold text-ink">
                  Reset Account Password
                </h1>
                <p className="text-xs text-muted">
                  Enter your registered email address to receive a single-use password reset link
                  valid for 60 minutes.
                </p>
                <Input
                  label="Registered Email Address"
                  type="email"
                  placeholder="name@college.edu"
                  value={email}
                  onChange={(e) => setEmail(e.target.value)}
                />
                {formNotice && (
                  <div className="rounded-[12px] border border-success/40 bg-success/10 p-3 text-xs text-success">
                    {formNotice}
                  </div>
                )}
                <div className="flex gap-2">
                  <Button
                    variant="primary"
                    className="flex-1"
                    onClick={() =>
                      setFormNotice(
                        'If an account exists for that email address, a password reset link has been dispatched.'
                      )
                    }
                  >
                    Send Reset Link
                  </Button>
                  <Button variant="secondary" onClick={() => setMode('login')}>
                    Back to Sign In
                  </Button>
                </div>
              </GlassCard>
            )}

            {/* LOCKOUT SCREEN */}
            {mode === 'locked' && (
              <GlassCard padding="lg" className="space-y-4 border-danger">
                <div className="flex items-center gap-2 text-danger">
                  <ShieldAlert className="h-5 w-5" strokeWidth={1.75} />
                  <span className="text-xs font-semibold">
                    Temporary Security Lockout (15 Minutes)
                  </span>
                </div>
                <h1 className="font-editorial text-2xl font-bold text-ink">
                  Account temporarily locked after 5 failed attempts.
                </h1>
                <p className="text-xs text-muted">
                  This event has been recorded in the Super Admin audit log. Please reset your
                  password or unlock below.
                </p>
                <Button
                  variant="secondary"
                  size="sm"
                  onClick={() => {
                    setFailedAttempts(0);
                    setFormError(null);
                    setMode('login');
                  }}
                >
                  Unlock &amp; Return to Sign In
                </Button>
              </GlassCard>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
